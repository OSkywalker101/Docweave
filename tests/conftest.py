"""Shared pytest fixtures.

Fixtures are built once per session into a temp directory. Nothing is
downloaded; every document is generated by ``tests/fixtures_builder.py``.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tests import diagram_corpus as diagram_corpus_module
from tests import fixtures_builder  # noqa: E402


def _has(module: str) -> bool:
    import importlib.util

    try:
        return importlib.util.find_spec(module) is not None
    except (ImportError, ValueError):
        return False


HAS_PDF = _has("pymupdf") or _has("fitz")
HAS_DOCX = _has("docx")
HAS_PPTX = _has("pptx")
HAS_XLSX = _has("openpyxl")
HAS_BS4 = _has("bs4")
HAS_CV2 = _has("cv2")
HAS_NUMPY = _has("numpy")
HAS_DIAGRAMS = HAS_CV2 and HAS_NUMPY


def _has_tesseract() -> bool:
    try:
        import pytesseract

        pytesseract.get_tesseract_version()
    except Exception:
        return False
    return True


#: Any OCR engine will do. Indra is preferred and Tesseract is the fallback, so
#: gating on Tesseract alone left the OCR tests skipping on a machine that had a
#: better engine installed -- a gate that reports "no capability" when the
#: capability is present.
HAS_OCR = _has("indra_ocr") or (_has("pytesseract") and _has_tesseract())

#: Separate, because page OCR and diagram labels use different engines. Indra
#: reads pages and cannot read a 63x12 label crop; Tesseract does both. A single
#: gate reported "OCR available" on a machine that could only do pages, and the
#: label tests failed instead of skipping.
HAS_TESSERACT = _has("pytesseract") and _has_tesseract()

requires_pdf = pytest.mark.skipif(not HAS_PDF, reason="pymupdf is not installed")
requires_docx = pytest.mark.skipif(not HAS_DOCX, reason="python-docx is not installed")
requires_pptx = pytest.mark.skipif(not HAS_PPTX, reason="python-pptx is not installed")
requires_xlsx = pytest.mark.skipif(not HAS_XLSX, reason="openpyxl is not installed")
requires_diagrams = pytest.mark.skipif(
    not HAS_DIAGRAMS, reason="opencv-python / numpy are not installed"
)
requires_ocr = pytest.mark.skipif(
    not HAS_OCR, reason="no OCR engine installed (indra-ocr or tesseract)"
)
requires_tesseract = pytest.mark.skipif(
    not HAS_TESSERACT, reason="tesseract is not installed"
)


@pytest.fixture(scope="session")
def corpus(tmp_path_factory) -> Path:
    """A directory holding every synthetic fixture."""
    target = tmp_path_factory.mktemp("corpus")
    fixtures_builder.build_all(target)
    return target


@pytest.fixture(scope="session")
def diagram_corpus(tmp_path_factory) -> Path:
    """A directory holding the synthetic diagram corpus."""
    target = tmp_path_factory.mktemp("diagrams")
    diagram_corpus_module.build_all(target)
    return target


@pytest.fixture(scope="session")
def diagram_specs():
    return diagram_corpus_module.specs_by_name()


@pytest.fixture
def fx(corpus: Path):
    """Callable returning the path of a named fixture."""
    def _get(name: str) -> Path:
        path = corpus / name
        if not path.exists():
            raise AssertionError(f"fixture '{name}' was not generated")
        return path

    return _get


@pytest.fixture
def scratch(tmp_path: Path) -> Path:
    return tmp_path
